static aes128_ctx_t g_ctx;

aes128_ctx_t *aes128_ctx_comum(void)
{
    return &g_ctx;
}

/* Multiplicacao por x em GF(2^8), sem desvio pelo bit alto. */
static uint8_t xtime(uint8_t a)
{
    return (uint8_t)((uint8_t)(a << 1) ^ (uint8_t)(0x1Bu & (uint8_t)(0u - (a >> 7))));
}

static uint8_t mul(uint8_t a, uint8_t b)
{
    uint8_t  r = 0u;
    uint32_t i;

    for (i = 0u; i < 8u; i++) {
        r ^= (uint8_t)(a & (uint8_t)(0u - (b & 1u)));
        a = xtime(a);
        b >>= 1;
    }
    return r;
}

int aes128_prepara(aes128_ctx_t *ctx, const uint8_t chave[AES128_CHAVE])
{
    uint8_t  rcon = 0x01u;
    uint32_t r, i;

    if ((ctx == 0) || (chave == 0)) {
        return -1;
    }
    for (i = 0u; i < 16u; i++) {
        ctx->rk[0][i] = chave[i];
    }
    for (r = 1u; r < 11u; r++) {
        const uint8_t *p = ctx->rk[r - 1u];
        uint8_t       *q = ctx->rk[r];
        /* RotWord, SubWord e Rcon sobre a ultima palavra da subchave anterior. */
        q[0] = (uint8_t)(p[0] ^ SBOX[p[13]] ^ rcon);
        q[1] = (uint8_t)(p[1] ^ SBOX[p[14]]);
        q[2] = (uint8_t)(p[2] ^ SBOX[p[15]]);
        q[3] = (uint8_t)(p[3] ^ SBOX[p[12]]);
        for (i = 4u; i < 16u; i++) {
            q[i] = (uint8_t)(p[i] ^ q[i - 4u]);
        }
        rcon = xtime(rcon);
    }
    return 0;
}

static void soma_chave(uint8_t s[16], const uint8_t k[16])
{
    uint32_t i;

    for (i = 0u; i < 16u; i++) {
        s[i] ^= k[i];
    }
}

/* SubBytes e ShiftRows juntos. O estado e por coluna: s[4c + l]. */
static void sub_desloca(uint8_t s[16], const uint8_t *caixa, int inversa)
{
    uint8_t  t[16];
    uint32_t c, l;

    for (c = 0u; c < 4u; c++) {
        for (l = 0u; l < 4u; l++) {
            /* Linha l desloca l posicoes: para a esquerda na cifra, para a
             * direita na decifra. */
            uint32_t orig = inversa ? ((c + 4u - l) & 3u) : ((c + l) & 3u);
            t[4u * c + l] = caixa[s[4u * orig + l]];
        }
    }
    for (c = 0u; c < 16u; c++) {
        s[c] = t[c];
    }
    wipe(t, sizeof t);
}

static void mistura(uint8_t s[16], int inversa)
{
    uint32_t c;

    for (c = 0u; c < 4u; c++) {
        uint8_t *v = &s[4u * c];
        uint8_t a0 = v[0], a1 = v[1], a2 = v[2], a3 = v[3];
        if (!inversa) {
            v[0] = (uint8_t)(mul(a0, 2u) ^ mul(a1, 3u) ^ a2 ^ a3);
            v[1] = (uint8_t)(a0 ^ mul(a1, 2u) ^ mul(a2, 3u) ^ a3);
            v[2] = (uint8_t)(a0 ^ a1 ^ mul(a2, 2u) ^ mul(a3, 3u));
            v[3] = (uint8_t)(mul(a0, 3u) ^ a1 ^ a2 ^ mul(a3, 2u));
        } else {
            v[0] = (uint8_t)(mul(a0, 14u) ^ mul(a1, 11u) ^ mul(a2, 13u) ^ mul(a3, 9u));
            v[1] = (uint8_t)(mul(a0, 9u) ^ mul(a1, 14u) ^ mul(a2, 11u) ^ mul(a3, 13u));
            v[2] = (uint8_t)(mul(a0, 13u) ^ mul(a1, 9u) ^ mul(a2, 14u) ^ mul(a3, 11u));
            v[3] = (uint8_t)(mul(a0, 11u) ^ mul(a1, 13u) ^ mul(a2, 9u) ^ mul(a3, 14u));
        }
    }
}

void aes128_bloco(const aes128_ctx_t *ctx, const uint8_t entrada[AES128_BLOCO],
                  uint8_t saida[AES128_BLOCO], int cifrar)
{
    uint8_t  s[16];
    uint32_t i, r;

    for (i = 0u; i < 16u; i++) {
        s[i] = entrada[i];
    }
    if (cifrar) {
        soma_chave(s, ctx->rk[0]);
        for (r = 1u; r < 10u; r++) {
            sub_desloca(s, SBOX, 0);
            mistura(s, 0);
            soma_chave(s, ctx->rk[r]);
        }
        sub_desloca(s, SBOX, 0);
        soma_chave(s, ctx->rk[10]);
    } else {
        soma_chave(s, ctx->rk[10]);
        for (r = 9u; r > 0u; r--) {
            sub_desloca(s, SBOX_INV, 1);
            soma_chave(s, ctx->rk[r]);
            mistura(s, 1);
        }
        sub_desloca(s, SBOX_INV, 1);
        soma_chave(s, ctx->rk[0]);
    }
    for (i = 0u; i < 16u; i++) {
        saida[i] = s[i];
    }
    wipe(s, sizeof s);
}

void aes128_apaga(aes128_ctx_t *ctx)
{
    if (ctx != 0) {
        wipe(ctx, sizeof *ctx);
    }
}
